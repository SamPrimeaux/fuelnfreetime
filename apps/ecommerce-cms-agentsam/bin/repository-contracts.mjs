#!/usr/bin/env node
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(appRoot, "../..");

function flag(name, fallback = null) {
  const i = process.argv.indexOf(name);
  return i === -1 ? fallback : process.argv[i + 1] ?? fallback;
}

function sqlText(value) {
  if (value == null) return "NULL";
  return "'" + String(value).replaceAll("'", "''") + "'";
}

function hashFile(buffer) {
  return createHash("sha256").update(buffer).digest("hex");
}

function stableId(repositoryId, contractKey, contractVersion) {
  const raw = repositoryId + ":" + contractKey + ":" + contractVersion;
  return "rct_" + createHash("sha1").update(raw).digest("hex").slice(0, 16);
}

const accountId = flag("--account-id") || process.env.AGENTSAM_REPOSITORY_ACCOUNT_ID;
const repositoryId = flag("--repository-id") || process.env.AGENTSAM_REPOSITORY_ID;
const output = path.resolve(
  flag(
    "--output",
    path.join(repoRoot, "db/seed-agentsam-repository-contracts.generated.sql"),
  ),
);

if (!accountId || !repositoryId) {
  throw new Error("--account-id and --repository-id are required");
}

const registry = JSON.parse(
  await readFile(path.join(appRoot, "repository.contracts.json"), "utf8"),
);

const rows = [];
for (const contract of registry.contracts || []) {
  const absolute = path.join(repoRoot, contract.manifest_path);
  const bytes = await readFile(absolute);
  rows.push({
    ...contract,
    contract_hash: hashFile(bytes),
    metadata_json: JSON.stringify({
      ...(contract.metadata || {}),
      hash_algorithm: "sha256",
    }),
  });
}

const valueRows = rows.map((row) => {
  const values = [
    sqlText(stableId(repositoryId, row.contract_key, row.contract_version)),
    sqlText(accountId),
    sqlText(repositoryId),
    sqlText(row.contract_key),
    sqlText(row.contract_version),
    sqlText(row.contract_type),
    sqlText(row.name),
    sqlText(row.description),
    sqlText(row.manifest_path),
    sqlText(row.contract_hash),
    sqlText(row.status || "active"),
    sqlText(row.metadata_json),
    "unixepoch()",
    "unixepoch()",
  ];
  return "(" + values.join(", ") + ")";
});

const sql =
  "-- GENERATED by apps/ecommerce-cms-agentsam/bin/repository-contracts.mjs\n" +
  "-- Source: apps/ecommerce-cms-agentsam/repository.contracts.json\n" +
  "INSERT INTO agentsam_repository_contracts (\n" +
  "  id, account_id, repository_id, contract_key, contract_version, contract_type,\n" +
  "  name, description, manifest_path, contract_hash, status, metadata_json,\n" +
  "  created_at, updated_at\n" +
  ") VALUES\n" +
  valueRows.join(",\n") +
  "\nON CONFLICT(repository_id,contract_key,contract_version) DO UPDATE SET\n" +
  "  account_id=excluded.account_id,\n" +
  "  contract_type=excluded.contract_type,\n" +
  "  name=excluded.name,\n" +
  "  description=excluded.description,\n" +
  "  manifest_path=excluded.manifest_path,\n" +
  "  contract_hash=excluded.contract_hash,\n" +
  "  status=excluded.status,\n" +
  "  metadata_json=excluded.metadata_json,\n" +
  "  updated_at=unixepoch();\n";

await writeFile(output, sql);
console.log(JSON.stringify({ ok: true, output, contracts: rows.length }, null, 2));
